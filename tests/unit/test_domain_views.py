"""The generated models are read-only (developer-tooling: Generated code is read-only)."""

from pathlib import Path

import pytest
from pydantic import ValidationError

from fingerprint.domain.views import NodeShape, PropertyShape

DOMAIN = Path(__file__).parents[2] / "fingerprint" / "domain"


def test_a_view_object_cannot_be_changed():
    shape = NodeShape(shape="<urn:s>", target="<urn:c>")
    with pytest.raises(ValidationError):
        shape.target = "<urn:d>"


def test_a_view_refuses_unknown_fields():
    with pytest.raises(ValidationError):
        PropertyShape(path="<urn:p>", severity="info", bogus=1)


@pytest.mark.parametrize("module", ["profile.py", "views.py"])
def test_generated_modules_carry_the_banner(module):
    first = (DOMAIN / module).read_text().splitlines()[0]
    assert first.startswith("# GENERATED by make generate-models") and "DO NOT EDIT" in first
