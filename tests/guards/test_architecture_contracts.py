"""A violating import breaks the named contract (developer-tooling: Onion layers are enforced)."""

from pathlib import Path

import pytest
from pydantic import ValidationError

from fingerprint.domain.profile import Failure, QueryKind

DOMAIN = Path(__file__).parents[2] / "fingerprint" / "domain"
LAYERS = "fingerprint layers"
GENERATED = "generated model imports no project code"


def test_a_service_layer_module_importing_an_entrypoint_breaks_the_layers_contract(tree, lint):
    (tree / "fingerprint" / "service_layer" / "violation.py").write_text("import fingerprint.entrypoints.cli.main\n")
    result = lint(tree)
    assert result.returncode != 0
    assert LAYERS in result.stdout


def test_a_domain_module_importing_an_adapter_breaks_the_layers_contract(tree, lint):
    (tree / "fingerprint" / "domain" / "violation.py").write_text("import fingerprint.adapters.sparql\n")
    result = lint(tree)
    assert result.returncode != 0
    assert LAYERS in result.stdout


def test_a_generated_module_importing_project_code_breaks_its_contract(tree, lint):
    profile = tree / "fingerprint" / "domain" / "profile.py"
    profile.write_text(profile.read_text() + "\nimport fingerprint.domain.analytics\n")
    result = lint(tree)
    assert result.returncode != 0
    assert GENERATED in result.stdout


def test_generated_modules_state_they_are_generated_on_the_first_line():
    for module in ("profile.py", "views.py"):
        first = (DOMAIN / module).read_text().splitlines()[0]
        assert first.startswith("# GENERATED by make generate-models") and "DO NOT EDIT" in first


def test_assigning_a_field_of_a_profile_object_raises_a_validation_error():
    failure = Failure(query_kind=next(iter(QueryKind)))
    with pytest.raises(ValidationError):
        failure.message = "changed"
